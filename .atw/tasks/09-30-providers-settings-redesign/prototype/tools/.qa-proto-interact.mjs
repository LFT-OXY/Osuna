import { chromium } from "playwright";
const DIR = "/Users/oxy/Documents/code/My/Osuna/.atw/tasks/09-30-providers-settings-redesign/prototype";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errs = []; page.on("pageerror", (e) => errs.push(e.message));
await page.goto(`file://${DIR}/providers-redesign.html`);
const name = () => page.locator(".dhead-name").first().innerText();
const check = (label, cond) => console.log(cond ? "PASS" : "FAIL", label);
await page.locator('.prow[data-id="codex"]').click(); check("点 Codex 行切换详情", (await name()) === "Codex");
await page.locator('.prow[data-id="copilot"] .sw-wrap').click();
check("开关切换且不改选中", (await name()) === "Codex" && (await page.locator('.prow[data-id="copilot"] .sw.on').count()) === 1);
await page.locator('[data-act="menu"]').first().click(); check("⋯ 打开菜单", (await page.locator(".menu").count()) === 1);
await page.locator('.menu [data-act="run-diag"]').click(); check("菜单诊断 → 诊断节展开", (await page.locator(".code").count()) === 1 && (await page.locator(".menu").count()) === 0);
await page.locator('[data-act="add-model"]').first().click(); check("添加 Model 就地展开", (await page.locator(".madd").count()) === 1);
await page.locator('[data-act="catalog"]').click(); check("「+」打开目录", (await page.locator(".dialog").count()) === 1);
await page.locator('[data-act="add-provider"][data-name="Amp"]').click();
check("添加后关弹窗并选中 Amp", (await page.locator(".dialog").count()) === 0 && (await name()) === "Amp");
await page.locator('.prow[data-id="pi"]').click(); await page.locator('[data-os="windows"]').click();
check("安装指引切到 Windows", (await page.locator(".cmd").first().innerText()).startsWith("npm install"));
await page.locator('[data-proto="theme"][data-v="dark"]').click(); check("切深色", (await page.locator(".frame.theme-dark").count()) === 1);
await page.locator('[data-proto="screen"][data-v="C1"]').click(); await page.locator('.prow[data-id="claude"]').click();
check("手机：点行推入详情", (await page.locator(".btitle").innerText()) === "Claude");
await page.locator('.bhdr [data-act="back"]').click(); check("手机：返回列表", (await page.locator(".btitle").innerText()) === "Providers");
await page.screenshot({ path: "/tmp/proto-page.png" });
console.log("errors:", errs.length ? errs : "none");
await browser.close();
